<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Client;
use App\Models\SystemNotification;
use App\Models\User;
use App\Services\MailNotificationService;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;

class ClientController extends Controller
{
    /**
     * List all clients with their projects, tickets and invoice stats.
     */
    public function index(Request $request)
    {
        $query = Client::with(['user', 'projects'])->withCount(['projects', 'tickets']);

        if ($request->filled('search')) {
            $search = $request->search;
            $query->where(function ($q) use ($search) {
                $q->where('name', 'like', "%{$search}%")
                  ->orWhere('company_name', 'like', "%{$search}%")
                  ->orWhere('email', 'like', "%{$search}%")
                  ->orWhere('client_code', 'like', "%{$search}%")
                  ->orWhere('phone', 'like', "%{$search}%");
            });
        }

        if ($request->filled('status')) {
            $query->where('portal_access_status', $request->status);
        }

        $clients = $query->orderBy('created_at', 'desc')->paginate($request->input('per_page', 20));

        $stats = [
            'total_clients' => Client::count(),
            'active_portal_users' => Client::where('portal_access_status', 'active')->count(),
            'total_active_projects' => Client::has('projects')->count(),
        ];

        return response()->json([
            'clients' => $clients,
            'stats' => $stats,
        ]);
    }

    /**
     * Store new client. Can optionally create Portal Login account.
     */
    public function store(Request $request)
    {
        $validated = $request->validate([
            'name' => 'required|string|max:255',
            'company_name' => 'required|string|max:255',
            'email' => 'required|email|unique:clients,email',
            'phone' => 'nullable|string|max:20',
            'gstin' => 'nullable|string|max:25',
            'pan' => 'nullable|string|max:20',
            'address' => 'nullable|string',
            'city' => 'nullable|string|max:100',
            'state' => 'nullable|string|max:100',
            'country' => 'nullable|string|max:100',
            'postal_code' => 'nullable|string|max:20',
            'currency' => 'nullable|string|max:10',
            'payment_terms' => 'nullable|string|max:50',
            'notes' => 'nullable|string',
            'create_portal_account' => 'nullable|boolean',
            'grant_mobile_access' => 'nullable|boolean',
            'send_invitation_email' => 'nullable|boolean',
        ]);

        $count = Client::count() + 1;
        $clientCode = 'CLI-' . date('Y') . '-' . str_pad($count, 3, '0', STR_PAD_LEFT);
        while (Client::where('client_code', $clientCode)->exists()) {
            $count++;
            $clientCode = 'CLI-' . date('Y') . '-' . str_pad($count, 3, '0', STR_PAD_LEFT);
        }

        $userId = null;
        $grantAccess = !empty($validated['grant_mobile_access']) || !empty($validated['create_portal_account']);
        $activationToken = null;

        if ($grantAccess) {
            // For security, password is NEVER generated by admin.
            // Client creates their own password via email link for mobile app.
            $placeholderHash = Hash::make(Str::random(32));
            $user = User::firstOrCreate(
                ['email' => $validated['email']],
                [
                    'name' => $validated['name'],
                    'role' => 'client',
                    'phone' => $validated['phone'] ?? null,
                    'password' => $placeholderHash,
                    'status' => 'active',
                ]
            );
            $userId = $user->id;

            // Generate 48-hour secure activation token
            $activationToken = bin2hex(random_bytes(32));
            \Illuminate\Support\Facades\DB::table('password_reset_tokens')->updateOrInsert(
                ['email' => $validated['email']],
                [
                    'token' => $activationToken,
                    'created_at' => now(),
                ]
            );
        }

        // Auto-extract PAN from GSTIN if not explicitly provided
        $pan = $validated['pan'] ?? null;
        if (empty($pan) && !empty($validated['gstin']) && strlen($validated['gstin']) >= 10) {
            $pan = substr($validated['gstin'], 2, 10);
        }

        $client = Client::create([
            'user_id' => $userId,
            'client_code' => $clientCode,
            'name' => $validated['name'],
            'company_name' => $validated['company_name'],
            'email' => $validated['email'],
            'phone' => $validated['phone'] ?? null,
            'gstin' => $validated['gstin'] ?? null,
            'pan' => $pan,
            'address' => $validated['address'] ?? null,
            'city' => $validated['city'] ?? null,
            'state' => $validated['state'] ?? 'West Bengal',
            'country' => $validated['country'] ?? 'India',
            'postal_code' => $validated['postal_code'] ?? null,
            'currency' => $validated['currency'] ?? 'INR',
            'payment_terms' => $validated['payment_terms'] ?? 'Net 30',
            'portal_access_status' => $grantAccess ? 'active' : 'inactive',
            'notes' => $validated['notes'] ?? null,
        ]);

        $client->load(['user', 'projects']);

        $shouldSendInvite = $grantAccess &&
            (!isset($validated['send_invitation_email']) || !empty($validated['send_invitation_email']));

        if ($shouldSendInvite && $activationToken) {
            try {
                MailNotificationService::sendClientInvitation($client, $activationToken);
            } catch (\Throwable $e) {
                \Illuminate\Support\Facades\Log::error("Failed to send client invitation email: " . $e->getMessage());
            }
        } else {
            SystemNotification::createNotification(
                null,
                'client',
                'New Client Added',
                "Client {$client->name} ({$client->company_name}) has been registered.",
                '/dashboard/clients'
            );
        }

        return response()->json([
            'message' => 'Client created successfully.',
            'client' => $client,
        ], 201);
    }

    /**
     * Show single client details.
     */
    public function show(Client $client)
    {
        $client->load(['user', 'projects.tasks', 'tickets.replies']);
        return response()->json(['client' => $client]);
    }

    /**
     * Update client profile.
     */
    public function update(Request $request, Client $client)
    {
        $validated = $request->validate([
            'name' => 'required|string|max:255',
            'company_name' => 'required|string|max:255',
            'email' => 'required|email|unique:clients,email,' . $client->id,
            'phone' => 'nullable|string|max:20',
            'gstin' => 'nullable|string|max:25',
            'pan' => 'nullable|string|max:20',
            'address' => 'nullable|string',
            'city' => 'nullable|string|max:100',
            'state' => 'nullable|string|max:100',
            'country' => 'nullable|string|max:100',
            'postal_code' => 'nullable|string|max:20',
            'currency' => 'nullable|string|max:10',
            'payment_terms' => 'nullable|string|max:50',
            'portal_access_status' => 'nullable|in:active,inactive',
            'notes' => 'nullable|string',
            'reset_portal_password' => 'nullable|string|min:6',
        ]);

        $pan = $validated['pan'] ?? $client->pan;
        if (empty($pan) && !empty($validated['gstin']) && strlen($validated['gstin']) >= 10) {
            $pan = substr($validated['gstin'], 2, 10);
        }

        $client->update([
            'name' => $validated['name'],
            'company_name' => $validated['company_name'],
            'email' => $validated['email'],
            'phone' => $validated['phone'] ?? null,
            'gstin' => $validated['gstin'] ?? null,
            'pan' => $pan,
            'address' => $validated['address'] ?? null,
            'city' => $validated['city'] ?? null,
            'state' => $validated['state'] ?? 'West Bengal',
            'country' => $validated['country'] ?? 'India',
            'postal_code' => $validated['postal_code'] ?? $client->postal_code,
            'currency' => $validated['currency'] ?? ($client->currency ?? 'INR'),
            'payment_terms' => $validated['payment_terms'] ?? ($client->payment_terms ?? 'Net 30'),
            'portal_access_status' => $validated['portal_access_status'] ?? $client->portal_access_status,
            'notes' => $validated['notes'] ?? null,
        ]);

        // If client doesn't have portal user account, or reset password is provided
        if ($client->user_id) {
            $user = User::find($client->user_id);
            if ($user) {
                $userUpdate = ['name' => $validated['name'], 'email' => $validated['email']];
                if (!empty($validated['reset_portal_password'])) {
                    $userUpdate['password'] = Hash::make($validated['reset_portal_password']);
                }
                $user->update($userUpdate);
            }
        } elseif (!empty($validated['reset_portal_password'])) {
            $user = User::create([
                'name' => $validated['name'],
                'email' => $validated['email'],
                'role' => 'client',
                'phone' => $validated['phone'] ?? null,
                'password' => Hash::make($validated['reset_portal_password']),
                'status' => 'active',
            ]);
            $client->update(['user_id' => $user->id]);
        }

        $client->load(['user', 'projects']);

        if (!empty($validated['reset_portal_password'])) {
            try {
                $baseUrl = MailNotificationService::getBaseUrl();
                $portalUrl = "{$baseUrl}/login";
                $html = '
                    <h2 style="margin: 0 0 12px; font-size: 18px; color: #0f172a; font-weight: 700;">Hello ' . htmlspecialchars($client->name) . ',</h2>
                    <p style="font-size: 14px; line-height: 1.6; color: #475569; margin: 0 0 20px;">
                        The password for your Kabhyan Client Portal account (<strong>' . htmlspecialchars($client->company_name) . '</strong>) has been reset by the system administration team.
                    </p>
                    <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 20px; margin: 20px 0;">
                        <table width="100%" cellpadding="6" cellspacing="0" border="0" style="font-size: 13px; color: #334155;">
                            <tr><td width="130" style="font-weight: 600; color: #64748b;">Login Email:</td><td><strong>' . htmlspecialchars($client->email) . '</strong></td></tr>
                            <tr><td style="font-weight: 600; color: #64748b;">New Password:</td><td><span style="background: #fef3c7; color: #92400e; padding: 2px 8px; border-radius: 4px; font-family: monospace; font-weight: 700;">' . htmlspecialchars($validated['reset_portal_password']) . '</span></td></tr>
                        </table>
                    </div>
                ';
                MailNotificationService::send($client->email, "Kabhyan Client Portal - Password Updated", $html, $client->name, $portalUrl, "Access Client Portal");
            } catch (\Throwable $e) {
                \Illuminate\Support\Facades\Log::error("Failed to send client password update email: " . $e->getMessage());
            }
        }

        return response()->json([
            'message' => 'Client updated successfully.',
            'client' => $client,
        ]);
    }

    /**
     * Delete client.
     */
    public function destroy(Client $client)
    {
        $client->delete();
        return response()->json(['message' => 'Client deleted successfully.']);
    }

    /**
     * Resend Account Activation / Mobile App Invitation link to client.
     */
    public function sendInvite(Client $client)
    {
        if (empty($client->email)) {
            return response()->json(['message' => 'Client has no email address configured.'], 422);
        }

        // Ensure user account exists
        $user = User::firstOrCreate(
            ['email' => $client->email],
            [
                'name' => $client->name,
                'role' => 'client',
                'phone' => $client->phone,
                'password' => Hash::make(Str::random(32)),
                'status' => 'active',
            ]
        );

        if (!$client->user_id) {
            $client->update(['user_id' => $user->id]);
        }

        // Generate 48-hour secure token
        $token = bin2hex(random_bytes(32));
        \Illuminate\Support\Facades\DB::table('password_reset_tokens')->updateOrInsert(
            ['email' => $client->email],
            [
                'token' => $token,
                'created_at' => now(),
            ]
        );

        try {
            MailNotificationService::sendClientInvitation($client, $token);
        } catch (\Throwable $e) {
            return response()->json([
                'message' => 'Failed to dispatch invitation email: ' . $e->getMessage(),
            ], 500);
        }

        return response()->json([
            'message' => "Invitation email with secure password creation link sent to {$client->email}.",
        ]);
    }
}

